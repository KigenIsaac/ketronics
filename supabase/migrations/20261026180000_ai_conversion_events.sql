-- Minimal, privacy-conscious funnel events for AI shopping recommendations.
CREATE TABLE IF NOT EXISTS public.ai_conversion_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL CHECK (event_type IN ('ai_recommendation_shown', 'ai_recommendation_clicked', 'add_to_cart', 'purchase')),
  session_id UUID NOT NULL,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  product_id UUID REFERENCES public.products(id) ON DELETE SET NULL,
  order_id UUID REFERENCES public.orders(id) ON DELETE SET NULL,
  source TEXT NOT NULL DEFAULT 'ai_assistant' CHECK (source IN ('ai_assistant', 'product_page', 'cart', 'checkout')),
  value_kes NUMERIC CHECK (value_kes IS NULL OR value_kes >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ai_conversion_events_created_at ON public.ai_conversion_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_conversion_events_type_created_at ON public.ai_conversion_events(event_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_conversion_events_product_id ON public.ai_conversion_events(product_id);
CREATE INDEX IF NOT EXISTS idx_ai_conversion_events_session_id ON public.ai_conversion_events(session_id);

ALTER TABLE public.ai_conversion_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ai_conversion_events FROM anon, authenticated;
GRANT SELECT, INSERT ON public.ai_conversion_events TO service_role;
